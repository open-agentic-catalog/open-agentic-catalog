// basePath validates a local hosting prefix without selecting a publication host.
export function basePath(value = process.env.DOCS_BASE ?? '/') {
  if (!/^\/(?:[a-zA-Z0-9_-]+\/)*$/.test(value)) throw new Error('DOCS_BASE must be / or slash-delimited path segments, e.g. /catalog/');
  return value;
}
export const base = basePath();
// Validate the rendered navigation, including autogenerated groups, not just config.
export function assertHandbookNavigation(links, manifest, base) {
  for (const entry of manifest) {
    const target = base + (entry.route ? entry.route + '/' : '');
    const count = links.filter(link => link === target).length;
    if (count !== 1) throw new Error(`Handbook navigation must include ${target} exactly once; found ${count}`);
  }
}
// pagePath chooses the authored file or build-owned Markdown/MDX projection.
export const pagePath = entry => entry.projection ? `${contentRoot}/generated/${entry.route}.${entry.diagrams ? 'mdx' : 'md'}` : entry.source;

// Offline package guides keep manual references readable without cross-package
// links. Only their registered site projection expands these explicit comments.
export function projectManualLinks(entry, text) {
  const projected = text.replace(/^<!-- manual-link: \[([^\]\r\n]*)\]\(([^()\r\n]*)\) -->$/gm, (_marker, label, target) => {
    const page = target.split('#')[0];
    const source = path.posix.normalize(path.posix.join(path.posix.dirname(entry.source ?? ''), page));
    if (!entry.projection || !/^[A-Za-z0-9][A-Za-z0-9 .,:;/&()'-]{0,159}$/.test(label) || target.length > 1024 ||
        !/^(?:\.\.?\/)*(?:[A-Za-z0-9_-]+\/)*[A-Za-z0-9_.-]+\.mdx?(?:#[a-z0-9-]+)?$/.test(target) ||
        !routes.has(source) || resolveLink(entry.source, target, '/') === null) {
      throw new Error(`Invalid manual-link target or label in ${entry.source ?? 'source'}`);
    }
    return `[${label}](${target})`;
  });
  if (/<!--\s*manual-link\b/.test(projected)) throw new Error(`Malformed manual-link marker in ${entry.source ?? 'source'}`);
  return projected;
}

// Root Markdown stays repository-readable; explicit diagram markers let its
// site projection reuse the same Astro/SVG components as authored MDX pages.
export function projectDiagrams(entry, text) {
  const imports = [];
  for (const name of entry.diagrams ?? []) {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`Invalid diagram component: ${name}`);
    const marker = `<!-- diagram: ${name} -->`;
    if (text.split(marker).length !== 2) throw new Error(`Expected one diagram marker: ${name}`);
    const component = path.posix.relative(path.posix.dirname(pagePath(entry)), `documentation/src/components/architecture/${name}.astro`);
    imports.push(`import ${name} from ${JSON.stringify(component)};`);
    text = text.replace(marker, `<${name} />`);
  }
  if (/<!--\s*diagram:/.test(text)) throw new Error('Unregistered diagram marker');
  // Linter directives are source metadata, not HTML or MDX content.
  return imports.length ? imports.join('\n') + '\n\n' + text.replace(/^<!-- markdownlint-[^\n]* -->\n/gm, '') : text;
}
export const routes = new Map(entries.flatMap(e => [e.source, ...(e.aliases ?? [])].map(source => [source, e.route])));
// omittedSections returns exact level-two sections excluded from a projection,
// failing when a configured heading is absent or ambiguous rather than leaking it.
export function omittedSections(entry, text) {
  const sections = text.split(/(?=^## )/m);
  return (entry.omitSections ?? []).map(heading => {
    const matches = sections.filter(section => section.startsWith(`## ${heading}\n`));
    if (matches.length !== 1) throw new Error(`Expected one excluded section in ${entry.source ?? 'source'}: ${heading}; found ${matches.length}`);
    return matches[0];
  });
}
// omittedAnchors identifies headings and explicit anchors removed with a section,
// so link rewriting cannot leave links to content omitted from the reader page.
export function omittedAnchors(entry, text) {
  return new Set(omittedSections(entry, text)
    .flatMap(section=>[
      ...[...section.matchAll(/^#{2,6} (.+)$/gm)].map(match=>slug(match[1])),
      ...[...section.matchAll(/<a id="([^"]+)"><\/a>/g)].map(match=>match[1]),
    ]));
}
const omitted = new Map(entries.filter(e=>e.omitSections).map(e=>[e.source,omittedAnchors(e,fs.readFileSync(path.join(root,e.source),'utf8'))]));
