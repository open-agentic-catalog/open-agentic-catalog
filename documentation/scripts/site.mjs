// walk lists files recursively and refuses symlink inputs instead of following
// them outside the selected documentation tree. Filesystem errors propagate.
export function walk(directory) {
  return fs.readdirSync(directory, {withFileTypes: true}).flatMap(e => {
    if (e.isSymbolicLink()) throw new Error(`Symlink is not a documentation input: ${path.join(directory,e.name)}`);
    return e.isDirectory() ? walk(path.join(directory,e.name)) : [path.join(directory,e.name)];
  });
}
// assertLocalRefs rejects non-fragment OpenAPI references before the renderer
// can fetch external schemas. It does not validate the referenced schema itself.
export function assertLocalRefs(value) {
  if (!value || typeof value !== 'object') return;
  for (const [key,item] of Object.entries(value)) {
    if (key === '$ref' && (typeof item !== 'string' || !item.startsWith('#/'))) throw new Error(`Non-local OpenAPI reference: ${item}`);
    assertLocalRefs(item);
  }
}
// validateEntries rejects route collisions, ambiguous source aliases and private
// inputs before preparation creates any reader projections.
export function validateEntries(items) {
  const seen = new Set();
  const sources = new Set();
  const lookups = new Set();
  for (const entry of items) {
    if (!/^(?:[a-z0-9-]+\/)*[a-z0-9-]*$/.test(entry.route) || entry.route.startsWith('api/')) throw new Error(`Invalid/reserved route: ${entry.route}`);
    if (seen.has(entry.route) || sources.has(entry.source)) throw new Error(`Duplicate route or source: ${entry.source}`);
    if (/(^|\/)(implementation-status\.md|todo\.md|done\.md|deferred\.md|continue\.md|AGENTS\.md|output|coverage|node_modules)(\/|$)/.test(entry.source) || entry.source.startsWith('todo/')) throw new Error(`Excluded source: ${entry.source}`);
    if (entry.source.startsWith('/') || entry.source.split('/').includes('..')) throw new Error(`Unsafe source: ${entry.source}`);
    for (const key of [entry.source,...(entry.aliases??[])]) {
      if (lookups.has(key)) throw new Error(`Ambiguous source alias: ${key}`);
      lookups.add(key);
    }
    seen.add(entry.route); sources.add(entry.source);
  }
}
// The canonical Markdown remains repository-readable. Only known reader pages
// become local routes; other source references retain their text without a
// fabricated public URL or a reader-visible build-system notice.
export function resolveLink(source, target, prefix = base) {
  if (target.startsWith('#') && omitted.get(source)?.has(target.slice(1))) return null;
  if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(target)) return target;
  const [file, fragment] = target.split('#');
  const absolute = path.posix.normalize(path.posix.join(path.posix.dirname(source), decodeURI(file)));
  const entry = entries.find(e=>e.source === absolute || e.aliases?.includes(absolute));
  if (fragment && omitted.get(entry?.source)?.has(fragment)) return null;
  if (routes.has(absolute)) return prefix + routes.get(absolute) + (routes.get(absolute) ? '/' : '') + (fragment ? '#' + fragment : '');
  if (downloads.includes(absolute)) return prefix + 'generated/' + absolute;
  return null;
}
// remarkRepositoryLinks rewrites Markdown AST links using the original source
// path, preserving labels for repository-only targets and rejecting unlisted images.
export function remarkRepositoryLinks() {
  return (tree, file) => {
    const filename = path.relative(root, file.history[0] ?? file.path ?? '');
    const entry = entries.find(e => pagePath(e) === filename);
    if (!entry) return; // The plugin owns its generated API AST.
    const definitions = new Map();
    // collect resolves reference-style links before their definition nodes are visited.
    function collect(node) {
      if (node.type === 'definition') definitions.set(node.identifier, node.url);
      node.children?.forEach(collect);
    }
    collect(tree);
    // visit changes link nodes in place without discarding formatting in their labels.
    function visit(node) {
      if (node.type === 'linkReference') {
        node.type = 'link'; node.url = definitions.get(node.identifier);
      }
      if (node.type === 'link' || node.type === 'image') {
        const resolved = resolveLink(entry.source, node.url);
        if (resolved === null) {
          if (node.type === 'image') throw new Error(`Unlisted image in ${entry.source}: ${node.url}`);
          // Keep code/emphasis within the label, but render a neutral inline
          // span: there is no public destination for this repository input.
          node.type = 'emphasis'; delete node.url;
          node.data = {hName:'span'};
        } else node.url = resolved;
      }
      node.children?.forEach(visit);
    }
    visit(tree);
  };
}
