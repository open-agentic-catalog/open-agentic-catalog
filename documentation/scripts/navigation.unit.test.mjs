import test from 'node:test';
import assert from 'node:assert/strict';
import { parseFragment } from 'parse5';
import { assertIconAssets, assertNavigationIcons } from './navigation.mjs';

const css = 'nav[aria-label="Main"] a[data-nav-icon="map"] { --catalog-nav-mask: url("../assets/navigation/map.svg"); }';
const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="M1 1h2v2Z"/></svg>';
const assets = new Map([['map.svg', svg]]);
const nodes = html => parseFragment(html).childNodes;
const manual = [{route:''}, {route:'architecture/decisions/example'}];
const icons = new Set(['map']);
const links = base => `<a href="${base}" data-nav-icon="map"><span>Welcome</span></a><a href="${base}architecture/decisions/example/" data-nav-icon="map"><span>Decision with a long label</span></a><a href="${base}api/operations/tags/service/"><span>Service</span></a><a href="${base}api/operations/read/">Read<span class="sl-badge">GET</span></a>`;

test('local mask inputs reject missing, mismatched, duplicated and unused SVGs', () => {
  assert.deepEqual(assertIconAssets(css, assets), icons);
  assert.throws(() => assertIconAssets(css, new Map()), /Missing local/);
  assert.throws(() => assertIconAssets(css.replace('map.svg', 'other.svg'), assets), /does not match/);
  assert.throws(() => assertIconAssets(css + css, assets), /Duplicate/);
  assert.throws(() => assertIconAssets(css, new Map([...assets, ['unused.svg', svg]])), /Unused/);
  assert.throws(() => assertIconAssets(css.replace('../assets/navigation/', 'https://example.org/'), assets), /Nonlocal navigation mask/);
  for (const target of ['url(https://example.org/icon.svg)', "url('https://example.org/icon.svg')"]) {
    assert.throws(() => assertIconAssets(css.replace('url("../assets/navigation/map.svg")', target), assets), /Nonlocal navigation mask/);
  }
});

test('navigation SVGs require bounded shapes without embedded resources or active elements', () => {
  for (const invalid of [svg.replace('0 0 24 24', '0 0 40 40'), svg.replace('<path', '<script'), svg.replace('<path', '<image href="https://example.org/icon"'), svg.replace('<path', '<path onclick="alert(1)"'), svg.replace('<path', '<path fill="url(https://example.org/icon)"'), svg.replace('d="M1 1h2v2Z"', 'd=""'), svg.replace(/<path.*\/>/, '')]) {
    assert.throws(() => assertIconAssets(css, new Map([['map.svg', invalid]])));
  }
});

test('manual and autogenerated links keep their names while API method badges remain undecorated at either base', () => {
  for (const base of ['/', '/catalog-check/']) {
    assertNavigationIcons(nodes(links(base)), manual, base, icons);
    assert.throws(() => assertNavigationIcons(nodes(links(base).replace('<span class="sl-badge">GET</span>', '')), manual, base, icons), /method badge/);
    assert.throws(() => assertNavigationIcons(nodes(links(base).replace('>GET<', '>UNKNOWN<')), manual, base, icons), /method badge/);
    assert.throws(() => assertNavigationIcons(nodes(links(base).replace('data-nav-icon="map"', '')), manual, base, icons), /Missing or unknown/);
    assert.throws(() => assertNavigationIcons(nodes(links(base).replace('data-nav-icon="map"', 'data-nav-icon="unknown"')), manual, base, icons), /Missing or unknown/);
    assert.throws(() => assertNavigationIcons(nodes(links(base).replace('Read<span', 'Read<i>icon</i><span').replace(`href="${base}api/operations/read/"`, `href="${base}api/operations/read/" data-nav-icon="map"`)), manual, base, icons), /native badges/);
  }
});

test('decorative icons cannot override native accessible names or introduce focus controls', () => {
  for (const attribute of ['aria-label="Icon"', 'aria-labelledby="icon"', 'aria-hidden="true"', 'role="img"', 'tabindex="-1"', 'title="Icon"']) {
    assert.throws(() => assertNavigationIcons(nodes(links('/').replace('<a ', `<a ${attribute} `)), manual, '/', icons), /accessibility/);
  }
  for (const extra of ['<svg><title>Map</title></svg>', '<button>Map</button>', '<span>Map</span>']) {
    assert.throws(() => assertNavigationIcons(nodes(links('/').replace('</a>', extra + '</a>')), manual, '/', icons));
  }
  assert.throws(() => assertNavigationIcons(nodes(links('/').replace('<span>Welcome</span>', '<span></span>')), manual, '/', icons), /Missing manual navigation label/);
  assert.throws(() => assertNavigationIcons(nodes(links('/')), manual, '/', new Set(['map', 'unused'])), /Unassigned/);
});
