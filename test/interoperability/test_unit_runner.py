class Fingerprint(unittest.TestCase):
    def test_embedded_smoke_sample_changes_invalidate_catalog_identity(self):
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            inputs = tuple(root / path.relative_to(r.ROOT) for path in r.CATALOG_INPUTS)
            card = root / "samples/cards/order-agent.json"
            card.parent.mkdir(parents=True)
            card.write_text('{"name":"Order Agent"}')
            with patch.object(r, "ROOT", root):
                before = r.fingerprint(inputs)
                card.write_text('{"name":"Changed Agent"}')
                self.assertNotEqual(r.fingerprint(inputs), before)

    def test_bytecode_is_ignored_but_source_bytes_and_names_remain_bound(self):
        with tempfile.TemporaryDirectory() as name, patch.object(r, "ROOT", Path(name)):
            root = Path(name)
            source = root / "helper.py"
            source.write_text("value = 1\n")
            before = r.fingerprint((root,))
            cache = root / "__pycache__"
            cache.mkdir()
            (cache / "helper.cpython-312.pyc").write_bytes(b"generated bytecode")
            (root / "helper.pyc").write_bytes(b"legacy generated bytecode")
            (root / "helper.pyo").write_bytes(b"optimized generated bytecode")
            self.assertEqual(r.fingerprint((root,)), before)
            source.write_text("value = 2\n")
            self.assertNotEqual(r.fingerprint((root,)), before)
            source.write_text("value = 1\n")
            source.rename(root / "renamed.py")
            self.assertNotEqual(r.fingerprint((root,)), before)


class CachedGo(unittest.TestCase):
    def test_resolves_pinned_cached_compiler_without_ambient_flags_or_downloads(self):
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            (root / "go.mod").write_text("module fixture\ngo 1.27.0\n")
            compiler = root / "modules/golang.org/toolchain@v0.0.1-go1.27.0.linux-amd64/bin/go"
            compiler.parent.mkdir(parents=True)
            compiler.touch()
            output = Result(0, json.dumps({"GOROOT": str(root / "old"), "GOVERSION": "go1.22.2",
                "GOMODCACHE": str(root / "modules"), "GOHOSTOS": "linux", "GOHOSTARCH": "amd64"}), "")
            with patch.object(r, "ROOT", root), patch.object(r, "run", side_effect=[output, Result(0, "go1.27.0\n", "")]) as run, patch.dict(r.os.environ, {
                "GOTOOLCHAIN": "go9.99.0+auto", "GOFLAGS": "-mod=mod", "GOROOT": "/ambient",
                "GOPROXY": "https://example.invalid", "GONOPROXY": "*", "GOWORK": "/ambient/go.work",
                "GOOS": "ambient", "GOARCH": "ambient",
            }):
                self.assertEqual(r.cached_go(), str(compiler))
            self.assertEqual(run.call_args_list[0].args, (["go", "env", "-json", "GOROOT", "GOVERSION",
                                                         "GOMODCACHE", "GOHOSTOS", "GOHOSTARCH"],))
            self.assertEqual(run.call_args_list[1].args, ([str(compiler), "env", "GOVERSION"],))
            for call in run.call_args_list:
                environment = call.kwargs["env"]
                self.assertEqual(environment["GOTOOLCHAIN"], "local")
                for setting in ("GOPROXY", "GOSUMDB", "GOENV", "GOWORK", "GOTELEMETRY"):
                    self.assertEqual(environment[setting], "off")
                for setting in ("GOFLAGS", "GOPRIVATE", "GONOPROXY", "GONOSUMDB"):
                    self.assertEqual(environment[setting], "")
                for setting in ("GOROOT", "GOOS", "GOARCH"):
                    self.assertNotIn(setting, environment)

    def test_matching_launcher_uses_its_compiler_without_requiring_module_cache(self):
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            (root / "go.mod").write_text("module fixture\ngo 1.27.0\n")
