class Archive(unittest.TestCase):
    @staticmethod
    def archive(names, kind=tarfile.REGTYPE):
        raw = io.BytesIO()
        with tarfile.open(fileobj=raw, mode="w:gz") as archive:
            for name in names:
                member = tarfile.TarInfo(name)
                member.type = kind
                member.size = 1 if kind == tarfile.REGTYPE else 0
                member.linkname = "/etc/passwd" if kind == tarfile.SYMTYPE else ""
                archive.addfile(member, io.BytesIO(b"x") if member.size else None)
        return raw.getvalue()

    def test_valid_and_mismatch(self):
        digest = hashlib.sha256(b"LICENSE\0" + hashlib.sha256(b"x").digest()).hexdigest()
        raw = self.archive(["repo/LICENSE"])
        with tempfile.TemporaryDirectory() as name:
            destination = Path(name)
            with patch.object(r, "SOURCE_DIGEST", digest):
                self.assertEqual(r.extract_source(raw, destination), digest)
            self.assertEqual((destination / "LICENSE").read_bytes(), b"x")
            with self.assertRaisesRegex(ValueError, "digest mismatch"):
                r.extract_source(raw, destination)
    def test_unsafe_members(self):
        for names, kind, rejection in [
            (["/absolute"], tarfile.REGTYPE, "unsafe source archive path"),
            (["repo/../escape"], tarfile.REGTYPE, "unsafe source archive path"),
            (["repo/link"], tarfile.SYMTYPE, "source archive contains a link or special file"),
            (["repo/file", "other/second"], tarfile.REGTYPE, "multiple source archive roots"),
            (["repo/file", "repo/file"], tarfile.REGTYPE, "duplicate source archive path"),
            (["repo/device"], tarfile.CHRTYPE, "source archive contains a link or special file"),
        ]:
            raw = self.archive(names, kind)
            with self.subTest(names=names), tempfile.TemporaryDirectory() as name:
                destination = Path(name)
                with self.assertRaisesRegex(ValueError, "^" + rejection + "$"):
                    r.extract_source(raw, destination)
                self.assertEqual(list(destination.iterdir()), [])


class Assertions(unittest.TestCase):
    def setUp(self):
        self.entries = [
            {"identifier": "urn:air:catalog.example.com:readiness:agent", "displayName": "Order Agent", "type": "application/a2a-agent-card+json", "data": {"nested": {"value": 9007199254740993}}},
            {"identifier": "urn:air:catalog.example.com:readiness:mcp", "displayName": "Order MCP", "type": q.MCP, "data": {"name": "Order MCP"}},
            {"identifier": "urn:air:catalog.example.com:readiness:skill", "displayName": "Order Skill", "type": "text/markdown", "url": "https://catalog.example.com/skill"},
        ]

    def response(self, entries=None, **fields):
        entries = self.entries if entries is None else entries
        return Result(0, json.dumps({"results": [dict(entry, score=90, source=q.PUBLIC + "/ard/v1/") for entry in entries], **fields}), "")

    def test_cases_and_valid_outputs(self):
        cases = {case["name"]: case for case in q.cases(self.entries)}
        self.assertEqual(len(cases), 13)
        q.validate(cases["all-results"], self.response(), self.entries)
        q.validate(cases["no-matches"], self.response([]), self.entries)
        q.validate(cases["limit-one"], self.response(self.entries[:1], pageToken="opaque"), self.entries)
        q.validate(cases["mcp-filter"], self.response(self.entries[1:2]), self.entries)
        q.validate(cases["private-missing"], Result(2, "", "Error: HTTP 401"), self.entries)
        q.validate(cases["human-output"], Result(0, "Order Agent", ""), self.entries)
        private = json.loads(self.response().stdout)
        for entry in private["results"]:
            entry["source"] = q.PRIVATE + "/ard/v1/"
        q.validate(cases["private-reader"], Result(0, json.dumps(private), ""), self.entries)
    def test_reject_drift(self):
        case = next(case for case in q.cases(self.entries) if case["name"] == "all-results")
        mutations = [lambda p: p["results"].pop(),
                     lambda p: p["results"].append(p["results"][0]),
                     lambda p: p["results"][0].update(type="wrong"),
                     lambda p: p["results"][0].update(data={}),
                     lambda p: p["results"][0].update(score=True),
                     lambda p: p["results"][0].update(source="wrong"),
                     lambda p: p.update(referrals=[{"identifier": "unexpected"}])]
        for mutate in mutations:
            payload = json.loads(self.response().stdout)
            mutate(payload)
            with self.subTest(payload=payload), self.assertRaises(AssertionError):
                q.validate(case, Result(0, json.dumps(payload), ""), self.entries)
        with self.assertRaises(AssertionError):
            q.validate({"status": 401}, Result(0, "", "HTTP 401"), self.entries)
        with self.assertRaises(AssertionError):
            q.validate({"status": 401}, Result(2, "private", "HTTP 401"), self.entries)
    def test_private_url_uses_private_snapshot(self):
        private = json.loads(json.dumps(self.entries))
        private[2]["url"] = q.PRIVATE + "/public/v1/artifacts/skill"
        payload = json.loads(self.response(private).stdout)
        for entry in payload["results"]:
            entry["source"] = q.PRIVATE + "/ard/v1/"
        result = Result(0, json.dumps(payload), "")
        case = dict(private=True, expected={entry["identifier"] for entry in private})
        q.validate(case, result, private)
        with self.assertRaisesRegex(AssertionError, "changed url"):
            q.validate(case, result, self.entries)
    def test_fixed_origins_and_redaction(self):
        for origin, path in [("https://external.example", "/"), (q.PUBLIC, "//other"), (q.PUBLIC, "relative")]:
            with self.assertRaises(ValueError):
                q.request(origin, path)
        self.assertNotIn("local-reader", q.redact("Bearer local-reader"))
    def test_failure_does_not_stop_remaining_cases(self):
        def fake(argv, **_):
            return Result(0, "hf-discover 1.3.7", "") if "--version" in argv else Result(2, "", "decoder failure")
        output = io.StringIO()
        with patch.object(q, "prepare"), patch.object(q, "request", return_value={"entries": self.entries}), patch.object(q, "run", side_effect=fake), contextlib.redirect_stdout(output):
            self.assertEqual(q.qualify(), 1)
        report = json.loads(output.getvalue())
        self.assertEqual((report["total"], report["passed"]), (35, 0))


class Supervisor(helpers.SupervisorFixture, unittest.TestCase):
    def test_configuration_and_security(self):
        value = r.configuration()
        self.assertEqual(value["database"]["driver"], "memory")
        self.assertEqual([host["mode"] for host in value["discovery"]["hosts"]], ["anonymous", "authenticated"])
        flags = r.safety_args("owned")
        for expected in ("--pull=never", "--read-only", "--cap-drop=ALL", "--log-driver=none", "--user=65532:65532"):
            self.assertIn(expected, flags)
        with patch.dict("os.environ", {"DOCKER_HOST": "tcp://remote:2375"}, clear=True), patch.object(r, "docker") as docker:
            with self.assertRaisesRegex(RuntimeError, "local Unix-socket"):
                r.local_daemon()
            docker.assert_not_called()
        remote = Result(0, '[{"Endpoints":{"docker":{"Host":"ssh://remote"}}}]', "")
        with patch.dict("os.environ", {"DOCKER_HOST": "unix:///local", "DOCKER_CONTEXT": "remote"}), patch.object(r, "docker", return_value=remote), self.assertRaises(RuntimeError):
            r.local_daemon()
        self.assertIn("--env=HTTP_PROXY=", flags)
        self.assertFalse(any(flag.startswith("--tmpfs") for flag in flags))
    def test_missing_and_invalid_stamp(self):
        with tempfile.TemporaryDirectory() as name, patch.object(r, "STAMP", Path(name) / "stamp"):
            for content in (None, "bad", "{}", "[]", json.dumps({"identity": r.tool_identity(), "image": 123})):
                if content is not None:
                    r.STAMP.write_text(content)
                with self.assertRaisesRegex(RuntimeError, "tools-install"):
                    r.installed_image()
    def test_report_integrity(self):
        report = {"cases": [helpers.passing_case(name) for name in sorted(r.EXPECTED_CASES)],
                  "passed": 35, "total": 35, "client_version": "hf-discover 1.3.7"}
        r.check_report(report, 0)
        for invalid in ({}, dict(report, cases=[]), dict(report, passed=12), dict(report, client_version="other")):
            with self.assertRaises(RuntimeError):
                r.check_report(invalid, 0)
        with self.assertRaises(RuntimeError):
            r.check_report(report, 1)
    def test_installation_probe_cleanup(self):
        for failure in (False, True):
            calls = []

            def fake(*args, **kwargs):
                calls.append(args)
                if failure and args[0] == "run":
                    raise RuntimeError("timeout")
                return Result(0, "version", "")

            with patch.object(r, "docker", side_effect=fake):
                if failure:
                    with self.assertRaisesRegex(RuntimeError, "timeout"):
                        r.installation_probe("image", "hf-discover", ["--version"])
                else:
                    self.assertEqual(r.installation_probe("image", "hf-discover", ["--version"]).stdout, "version")
            self.assertIn("--network=none", calls[0])
            self.assertEqual(calls[-1][:2], ("rm", "-f"))
            self.assertIn(calls[-1][-1], calls[0])
    def test_all_outcomes_clean_owned_resources(self):
        for failure, expected in [(None, "passed"), ("case", "qualification-failed"), ("build", "setup-failed"), ("interrupt", "interrupted"), ("traversal-interrupt", "interrupted"), ("cleanup", "cleanup-failed")]:
            with self.subTest(failure=failure):
                code, report = self.exercise(failure)
                self.assertEqual(report["status"], expected)
                self.assertEqual(code, int(failure is not None))

    def test_source_changes_reject_an_otherwise_successful_qualification_and_clean_up(self):
        for failure in ("catalog-drift", "harness-drift"):
            with self.subTest(failure=failure):
                code, report = self.exercise(failure)
                self.assertEqual(code, 1)
                self.assertEqual(report["status"], "setup-failed")
                self.assertIn("source changed during qualification", report["error"])
                self.assertEqual(report["qualification"]["passed"], 35)
                self.assertNotIn("cleanup_errors", report)
