"""Explicit real-tool qualification; acquires the fixed pin, never auto-discovered."""

import argparse
from collections import Counter
from pathlib import Path
import signal
import sys
import tempfile

import mutation as m
import property as properties

PACKAGE = "example.com/policy"
SOURCE = 'package policy\nimport _ "embed"\n//go:embed fixture.txt\nvar fixture string\nfunc Allowed(n int) bool { return n >= 5 }\n'
TEST = 'package policy\nimport "testing"\nfunc TestPolicy(t *testing.T) { if fixture != "fixture" || !Allowed(5) || Allowed(0) { t.Fatal("boundary or embed") } }\n'


def qualify(go, toolchain):
    go, env = m.tool_environment(go, toolchain)
    with tempfile.TemporaryDirectory(prefix="mutation-qualification-") as directory:
        work = Path(directory)
        tool, _ = m.acquire(go, env, work / "bin")
        # An unrelated parent repository must not affect test-binary stamping.
        (work / ".git").mkdir()
        for case in ("strong", "weak", "skipped", "failed", "rapid-strong", "rapid-starved", "rapid-ignored"):
            root, output = work / case, work / (case + "-evidence")
            root.mkdir()
            output.mkdir()
            (root / "go.mod").write_text("module " + PACKAGE + "\n\ngo 1.27.0\n")
            (root / "policy.go").write_text(SOURCE)
            (root / "fixture.txt").write_text("fixture")
            test = TEST.replace("Allowed(5)", "Allowed(9)") if case == "weak" else TEST
            if case == "skipped":
                test = 'package policy\nimport "testing"\nfunc TestPolicy(t *testing.T) { _ = Allowed(5); t.Skip("no assertions") }\n'
            if case == "failed":
                test = TEST.replace('fixture != "fixture"', 'fixture == "fixture"')
            if case.startswith("rapid-"):
                (root / "go.mod").write_text("module " + PACKAGE + "\n\ngo 1.27.0\n\nrequire pgregory.net/rapid v1.3.0\n")
                m.run([go, "mod", "download", "pgregory.net/rapid@v1.3.0"], env, root)
                test = '''package policy
import ("testing"; "pgregory.net/rapid")
func TestPropertyPolicy(t *testing.T) { rapid.Check(t, func(t *rapid.T) {
n := rapid.IntRange(0,9).Draw(t,"n")
if Allowed(n) != (n >= 5) { t.Fatal("wrong policy decision") }
}) }
'''
                if case == "rapid-starved":
                    test = test.replace('rapid.IntRange(0,9)', 'rapid.IntRange(0,9).Filter(func(n int) bool { return n > 10 })')
                if case == "rapid-ignored":
                    corpus = root / "testdata/rapid/TestPropertyPolicy"
                    corpus.mkdir(parents=True)
                    (corpus / "TestPropertyPolicy-bad.fail").write_text("not a replay file")
            # A different test stem must not suppress policy.go.
            (root / "boundary_test.go").write_text(test)
            for tag in ("functional", "integration", "helm"):
                (root / (tag + "_test.go")).write_text('//go:build ' + tag + '\n\npackage policy\nimport "testing"\nfunc Test' + tag.title() + '(t *testing.T) { t.Fatal("excluded") }\n')
            (root / "generated.go").write_text('// Code generated by qualification. DO NOT EDIT.\npackage policy\nfunc Generated(n int) bool { return n > 0 }\n')
            (root / "excluded.go").write_text('//go:build functional\n\npackage policy\nfunc Excluded(n int) bool { return n > 0 }\n')
            child = root / "child"
            child.mkdir()
            (child / "bad_test.go").write_text('package child\nimport "testing"\nfunc TestChild(t *testing.T) { t.Fatal("excluded child") }\n')
            try:
                result = m.measure(root, output, ("policy.go",), PACKAGE, go, env, tool)
            except m.Failure:
                m.require(case in {"failed", "skipped", "rapid-starved", "rapid-ignored"}, "unexpected qualification failure")
                m.require(not (output / "inventory").exists(), "failed baseline reached mutation generation")
                baseline = output / "baseline"
                expected_failures = ["TestPolicy"] if case == "failed" else ["TestPropertyPolicy"] if case == "rapid-starved" else []
                m.require(m.decode(m.read(baseline / "result.json")) ==
                          {"status": "error", "failedTests": expected_failures},
                          "baseline rejection lacks the expected test result")
                events = [m.decode(line) for line in m.read(baseline / "baseline.events.jsonl").splitlines()]
                action = "fail" if case in {"failed", "rapid-starved"} else "pass" if case == "rapid-ignored" else "skip"
                name = "TestPropertyPolicy" if case.startswith("rapid-") else "TestPolicy"
                m.require(any(e.get("Package") == PACKAGE and e.get("Test") == name and
                              e.get("Action") == action for e in events),
                          "baseline fixture did not execute the expected test")
            else:
                wanted = {"caught": 2} if case in {"strong", "rapid-strong"} else {"caught": 1, "survived": 1}
                actual = dict(Counter(r["status"] for r in result))
                m.require(case in {"strong", "weak", "rapid-strong"} and actual == wanted,
                          f"native outcome mismatch for {case}: {actual}, expected {wanted}")
                if case == "rapid-strong":
                    settings = m.decode(m.read(output / "properties.json"))
                    m.require(settings["tests"] == ["TestPropertyPolicy"] and
                              settings["settings"] == properties.settings("100", "1") and settings["corpus"] == {},
                              "Rapid run identity mismatch")
            m.require((root / "policy.go").read_text() == SOURCE, "source modified")
            print("Qualified native " + case, flush=True)

        root = work / "strong"
        temporary = root / ".mutation-tmp"
        for case, replacement, expected in [
            ("panic", 'panic("broken invariant")', "caught"),
            ("compile", "return n + true", "error"),
            ("timeout", "for {}", "timeout"),
            ("missing-executor", "return n > 5", "error"),
            ("signal", "return n > 5", "error"),
        ]:
            evidence = work / ("control-" + case)
            evidence.mkdir()
            changed = temporary / (case + ".go")
            changed.write_text(SOURCE.replace("return n >= 5", replacement))
            selected_go = go
            if case in {"missing-executor", "signal"}:
                executor = evidence / "executor"
                if case == "signal":
                    executor.write_text('#!/usr/bin/env python3\nimport os,signal\nos.kill(os.getpid(),signal.SIGKILL)\n')
                    executor.chmod(0o700)
                wrapper = evidence / "go"
                wrapper.write_text('#!/usr/bin/env python3\nimport os,sys\nos.execv(' + repr(go) + ',[' + repr(go) + ',"test","-exec=' + str(executor) + '",*sys.argv[2:]])\n')
                wrapper.chmod(0o700)
                selected_go = str(wrapper)
            config = evidence / "config.json"
            m.write_json(config, dict(root=str(root), evidence=str(evidence), mode="execute", go=selected_go,
                temporary=str(temporary), package=PACKAGE, sources={"policy.go": m.sha(SOURCE.encode())}))
            selected_env = dict(env, CATALOG_MUTATION_HOOK=str(config), MUTATE_ORIGINAL=str(root / "policy.go"),
                                MUTATE_CHANGED=str(changed), MUTATE_PACKAGE=PACKAGE)
            try:
                m.run([sys.executable, "-I", "-B", str(Path(m.__file__).with_name("mutation_exec.py"))], selected_env, root, 65)
            except m.Failure:
                m.require(expected != "caught", "assertion control failed")
            records = [m.decode(m.read(p)) for p in evidence.glob("*.result.json")]
            m.require(len(records) == 1 and records[0]["status"] == expected, "hook control misclassified: " + case)
            print("Qualified hook " + case, flush=True)
    print("Mutation tool qualification passed; all owned fixtures removed.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--go", default="go")
    parser.add_argument("--toolchain", required=True)
    args = parser.parse_args()
    for sig in (signal.SIGTERM, signal.SIGINT):
        signal.signal(sig, m.interrupt)
    qualify(args.go, args.toolchain)
