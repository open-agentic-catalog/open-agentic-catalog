"""Explicit qualification of an installed pinned analyzer; never auto-discovered."""

import argparse
import os
from pathlib import Path
import tempfile

import dead_code


def qualify(tool, go, toolchain, version):
    env = dict(os.environ, GOTOOLCHAIN=toolchain, GOWORK="off", GOFLAGS="-mod=readonly", GOPACKAGESDRIVER="off", GOOS="linux", GOARCH="amd64", CGO_ENABLED="0")
    tool = str(Path(tool).resolve(strict=True))
    metadata = dead_code.run([go, "version", "-m", tool], dead_code.ROOT, env)
    if f"\tmod\tgolang.org/x/tools\t{version}\t" not in metadata or f": {toolchain}\n" not in metadata or f"\tpath\t{dead_code.TOOL}\n" not in metadata:
        raise ValueError("qualification requires the pinned analyzer and Go toolchain")
    with tempfile.TemporaryDirectory(prefix="catalog-deadcode-qualification-") as directory:
        root = Path(directory)
        files = {
            "go.mod": "module example.com/fixture\n\ngo 1.27.0\n",
            "cmd/api/main.go": 'package main\nimport "example.com/fixture/lib"\nfunc main(){lib.Live()}\n',
            "cmd/worker/main.go": 'package main\nimport "example.com/fixture/lib"\nfunc main(){lib.Worker()}\n',
            "lib/code.go": 'package lib\nfunc Live(){}\nfunc Worker(){}\nfunc TestOnly(){}\nfunc Tagged(){}\n//nolint:unused\nfunc Unused(){}\n',
            "lib/code_test.go": 'package lib\nimport "testing"\nfunc TestLibrary(t *testing.T){TestOnly()}\n',
            "lib/tagged_test.go": '//go:build functional\n\npackage lib\nimport "testing"\nfunc TestTagged(t *testing.T){Tagged()}\n',
            "lib/generated.go": '// Code generated by qualification. DO NOT EDIT.\npackage lib\nfunc Generated(){}\n',
            "orphan/code.go": 'package orphan\nfunc Orphan(){}\n',
            "specs/noise/broken.go": 'deliberately invalid ignored clone\n',
        }
        for name, body in files.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body)

        def scan(packages, flags=()):
            raw = dead_code.run([tool, "-json", "-filter=^example.com/fixture/", *flags, *packages], root, env)
            # Generated-reporting qualification intentionally bypasses the gate's
            # default-only report parser; retain the upstream marker evidence.
            return raw, {(p["Path"], f["Name"]) for p in dead_code.decode(raw) or [] for f in p["Funcs"]}

        lib = "example.com/fixture/lib"
        _, api = scan(["./cmd/api"])
        _, commands = scan(["./cmd/..."])
        if (lib, "Worker") not in api or (lib, "Worker") in commands:
            raise ValueError("worker executable root was not respected")
        _, complete = scan(["./cmd/...", "./lib/...", "./orphan/..."])
        if ("example.com/fixture/orphan", "Orphan") in commands or ("example.com/fixture/orphan", "Orphan") not in complete:
            raise ValueError("orphan package was not included in complete loading")
        _, command_tests = scan(["./cmd/..."], ["-test"])
        _, units = scan(["./cmd/...", "./lib/..."], ["-test"])
        _, functional = scan(["./cmd/...", "./lib/..."], ["-test", "-tags=functional"])
        if (lib, "TestOnly") not in command_tests or (lib, "TestOnly") in units or (lib, "Tagged") not in units or (lib, "Tagged") in functional:
            raise ValueError("dependency tests or functional build selection changed")
        if functional != {(lib, "Unused")}:
            raise ValueError("findings, comment suppression or generated defaults changed")
        generated_raw, generated = scan(["./cmd/...", "./lib/..."], ["-test", "-tags=functional", "-generated"])
        if (lib, "Generated") not in generated or '"Generated": true' not in generated_raw:
            raise ValueError("generated reporting changed")
        (root / "lib/code.go").write_text(files["lib/code.go"].replace("func Unused(){}", ""))
        clean, _ = scan(["./cmd/...", "./lib/..."], ["-test", "-tags=functional"])
        if clean.strip() != "null":
            raise ValueError("clean output format changed")
        for flags, packages in [([], ["./missing"]), (["-filter=["], ["./cmd/..."])]:
            try:
                dead_code.run([tool, "-json", *flags, *packages], root, env)
            except ValueError:
                pass
            else:
                raise ValueError("invalid analyzer input succeeded")
    print("Pinned analyzer qualification passed: executable roots, orphan packages, dependency tests, tags, generated output, comment behavior, null/findings and load errors; ignored clone not loaded.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tool", required=True)
    parser.add_argument("--go", default="go")
    parser.add_argument("--toolchain", required=True)
    parser.add_argument("--version", required=True)
    arguments = parser.parse_args()
    qualify(arguments.tool, arguments.go, arguments.toolchain, arguments.version)
